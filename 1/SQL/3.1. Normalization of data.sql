-- 3.1. Normalization of Vehicle Types and Contributing Factors
-- -----------------------------------------------------------------------------------------------------------------
-- Standardizes vehicle type and contributing factor values in the accidents table.
-- The source data contains inconsistent vehicle descriptions and contributing
-- factor names, which are normalized into a smaller set of standardized
-- categories.
--
-- The vehicle type normalization is applied separately to all five vehicle
-- type columns: VEHICLE_TYPE_CODE_1 through VEHICLE_TYPE_CODE_5.
-- LOWER() is used to make the matching case-insensitive, while LIKE is used
-- to identify different text patterns referring to the same vehicle category.
-- Examples include different descriptions of buses, trucks, vans, bicycles,
-- scooters, motorcycles, taxis, and other vehicle types.
--
-- The contributing factor normalization is applied separately to all five
-- contributing factor columns: CONTRIBUTING_FACTOR_VEHICLE_1 through
-- CONTRIBUTING_FACTOR_VEHICLE_5.
-- Different descriptions referring to the same reported contributing factor
-- are grouped into standardized categories such as distraction, driving
-- under influence, excessive speed, driver fatigue, improper maneuvers,
-- non-vehicular failure or defect, and vehicular failure or defect.
--
-- CASE expressions are used to evaluate the original text values and replace
-- matching values with standardized category names.
-- The ELSE clause preserves the original value when none of the defined
-- conditions is satisfied.
--
-- The resulting standardized values provide a consistent structure for
-- further SQL analysis and Power BI reporting.
-- -----------------------------------------------------------------------------------------------------------------

UPDATE accidents
SET
    BOROUGH = COALESCE(BOROUGH, 'NO BOROUGH'),
    ZIP_CODE = COALESCE(ZIP_CODE, 'NO ZIP CODE'),
    LATITUDE = COALESCE(LATITUDE, 0),
    LONGITUDE = COALESCE(LONGITUDE, 0),
    LOCATION = COALESCE(LOCATION, 0),
    ON_STREET_NAME = COALESCE(ON_STREET_NAME, 'NO STREET NAME'),
    CROSS_STREET_NAME = COALESCE(CROSS_STREET_NAME, 'NO STREET NAME'),
    OFF_STREET_NAME = COALESCE(OFF_STREET_NAME, 'NO STREET NAME'),
    CONTRIBUTING_FACTOR_VEHICLE_1 = COALESCE(CONTRIBUTING_FACTOR_VEHICLE_1, 'NO CONTRIBUTING FACTOR'),
    CONTRIBUTING_FACTOR_VEHICLE_2 = COALESCE(CONTRIBUTING_FACTOR_VEHICLE_2, 'NO CONTRIBUTING FACTOR'),
    CONTRIBUTING_FACTOR_VEHICLE_3 = COALESCE(CONTRIBUTING_FACTOR_VEHICLE_3, 'NO CONTRIBUTING FACTOR'),
    CONTRIBUTING_FACTOR_VEHICLE_4 = COALESCE(CONTRIBUTING_FACTOR_VEHICLE_4, 'NO CONTRIBUTING FACTOR'),
    CONTRIBUTING_FACTOR_VEHICLE_5 = COALESCE(CONTRIBUTING_FACTOR_VEHICLE_5, 'NO CONTRIBUTING FACTOR'),
    VEHICLE_TYPE_CODE_1 = COALESCE(VEHICLE_TYPE_CODE_1, 'NO VEHICLE TYPE CODE'),
    VEHICLE_TYPE_CODE_2 = COALESCE(VEHICLE_TYPE_CODE_2, 'NO VEHICLE TYPE CODE'),
    VEHICLE_TYPE_CODE_3 = COALESCE(VEHICLE_TYPE_CODE_3, 'NO VEHICLE TYPE CODE'),
    VEHICLE_TYPE_CODE_4 = COALESCE(VEHICLE_TYPE_CODE_4, 'NO VEHICLE TYPE CODE'),
    VEHICLE_TYPE_CODE_5 = COALESCE(VEHICLE_TYPE_CODE_5, 'NO VEHICLE TYPE CODE');

