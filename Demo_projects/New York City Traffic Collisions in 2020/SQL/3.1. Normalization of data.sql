-- 3.1. Preparing Location Fields and Standardizing Categories
-- -----------------------------------------------------------------------------------------------------------------
-- Updates location fields, vehicle types and contributing factors in the
-- accidents table after import. The preparation process:
--   - replaces selected missing location attributes with placeholder values,
--   - fills missing factor and vehicle descriptions before classification,
--   - applies ordered text-matching rules to each of the five vehicle fields,
--   - applies factor rules separately to each of the five factor fields.
--
-- Missing boroughs become NO BOROUGH, ZIP codes become NO ZIP CODE and
-- street names become NO STREET NAME. Missing coordinates become zero.
-- LOCATION is a text column, so its numeric replacement is stored as text.
-- These replacements mark missing information; they do not establish an
-- actual coordinate or street location. Date, time and casualty counts are
-- not filled by this script.
--
-- Vehicle rules produce categories such as AMBULANCE, BIKE, BUS, SEDAN,
-- SUV, TAXI, TRUCK and VAN. Factor rules group descriptions into categories
-- such as distraction, excessive speed, fatigue and vehicle defects.
-- The first matching condition determines the assigned category. Values
-- that match no condition become OTHER; their original text is not retained.
-- The missing-value placeholders are also processed by these rules and
-- become NO TYPE or NO FACTOR.
--
-- Factor patterns are written in uppercase although input text is converted
-- to lowercase. Their matching relies on the case-insensitive collation of
-- the source columns. The existing condition order is retained, including
-- the different position of the %LESS% factor rule in field 1 and fields 2-5.
--
-- All updates affect the current accidents table. The original descriptions
-- are overwritten, so the source CSV remains the reference for those values.
-- -----------------------------------------------------------------------------------------------------------------


